"""Shared constants and utilities for the Almond Axol robot."""

from enum import Enum
from pathlib import Path


class Joint(Enum):
    """All motor joints on one arm, in control order.

    The seven arm joints (``SHOULDER_1`` through ``WRIST_3``) are collected in
    ``ARM_JOINTS``. ``GRIPPER`` is the eighth entry and is handled separately
    from the arm joints throughout the control stack.
    """

    SHOULDER_1 = "shoulder_1"
    SHOULDER_2 = "shoulder_2"
    SHOULDER_3 = "shoulder_3"
    ELBOW = "elbow"
    WRIST_1 = "wrist_1"
    WRIST_2 = "wrist_2"
    WRIST_3 = "wrist_3"
    GRIPPER = "gripper"


CAN_LEFT = "can_alm_axol_l"
CAN_RIGHT = "can_alm_axol_r"
# The Jelly's wheel bus (its own single-channel adapter, separate from
# the arm hub), carrying the four Damiao wheel motors at IDs 0x01-0x04.
# NB: kernel interface names are capped at 15 chars (IFNAMSIZ), so this can't
# be the more readable "can_alm_axol_base".
CAN_BASE = "can_alm_axol_b"
# The chest bus (another single-channel adapter): the jelly_legs lift
# controller — our own PCB replacing the Jiecang control box, driving the
# telescoping lift legs (see almond_axol/robot/lift.py for the protocol).
# Optional: a Jelly may instead wire the lift controller onto the wheel bus
# (its IDs 0x420-0x422 are clear of every Damiao range), in which case this
# interface does not exist and the lift driver uses CAN_BASE — see
# almond_axol.robot.lift.resolve_lift_channel.
CAN_CHEST = "can_alm_axol_c"

# CAN bring-up script written by `axol can.setup`. Runs at boot and on adapter
# hotplug, and is also the sanctioned way to reset the interfaces at runtime:
# it flaps both arm-hub channels *together* (flapping one at a time can wedge
# the adapter's RX path). The CAN bus layer reuses it to purge stale TX frames
# after an e-stop (see almond_axol/motor/bus.py). It is executed as root by
# cron/systemd, so it must live outside the operator-writable state tree.
CAN_BRINGUP_SCRIPT: Path = Path("/etc/almond-axol/can/startup.sh")

# USB-resets the arm hub, then runs CAN_BRINGUP_SCRIPT. The hub's firmware
# keeps up to 10 frames per channel through the driver's link-down reset and
# transmits them on the next open (kernel: "Unexpected unused echo id"), so a
# flap cannot purge frames queued behind a stalled bus; this is what the
# purge runs instead. Written by `axol can.setup`, root-owned like the above.
CAN_RESET_SCRIPT: Path = Path("/etc/almond-axol/can/reset_adapter.sh")

# Mantis handheld data-collection rig: one dual-channel adapter, each channel
# wired to a single Damiao gripper (CAN ID 0x08, same as Joint.GRIPPER).
CAN_MANTIS_LEFT = "can_mantis_l"
CAN_MANTIS_RIGHT = "can_mantis_r"

ARM_JOINTS: list[Joint] = [j for j in Joint if j != Joint.GRIPPER]

# Fields per joint slot in a realtime-core command tuple — what an
# ``AxolArm`` command sink hands to ``almond_axol.rt`` and what one ``T``
# target slot carries on the wire: ``(p_des, mode, kp, kd, t_ff, kd_host,
# damp_w0, damp_q, j_eff, tau_cap)``. The gripper slot repurposes the first
# three (target, max_speed, max_torque) and zero-pads the rest. Must match
# ``TARGET_FIELDS`` in ``rust/axol-rt/src/serve.rs``; the core's config
# handshake (``proto``, ``almond_axol.rt.link.CONFIG_PROTO``) rejects a
# mismatch, so bump that together with any change here.
RT_TARGET_FIELDS = 10

# Cap on the return-to-rest a flow plays while shutting down, before it torques
# the arms off. It has to cover the IK plan plus a full return from a raised
# pose: rest moves play at ``reset_speed`` (0.63 rad/s on the worst joint,
# 1.5 s minimum), so a shoulder 2 rad up is ~3.2 s of motion alone. The serve
# runner's 6 s stop grace (``_STOP_GRACE_S``) is not a hard limit on this: past
# it the runner only kills the op's child processes (IK worker, video relay),
# and by then the plan is made and playback runs in-process. A park that
# overruns is abandoned and the arms are torqued off where they are — the
# pre-existing behaviour — so the cap can never make shutdown worse.
PARK_TIMEOUT_S: float = 6.0


class AxolModel(str, Enum):
    """Which Axol hardware version a robot is — selects its URDF.

    Every version shares the same arms: link frames, joint axes and inertials
    are identical, so forward kinematics, recorded Cartesian frames and
    gravity compensation do not depend on the version. What differs is the
    body the arms must not collide with and a few joint limits:

    - ``CLASSIC``: the original (legacy) Axol model (``axol.urdf``).
    - ``STANDALONE``: Axol on its own — the shoulder bar and head camera,
      nothing below them (``axol_standalone.urdf``).
    - ``OX_CART``: Axol on the Ox cart's lift column (``axol_ox_cart.urdf``;
      the lift fully raised).
    - ``OWL``: Axol on the Owl mount, a column on a foot plate
      (``axol_owl.urdf``).
    - ``MOBILE``: Axol on the Jelly mobile base (``axol_jelly.urdf``).

    All but ``CLASSIC`` are generated by ``scripts/build_jelly_urdfs.py``
    from the Onshape exports, with the head camera and wrist cameras, and
    their elbows reach 24 degrees further past straight.

    A robot is the mobile Axol exactly when Jelly is enabled; otherwise it is
    the mount saved as ``kinematics.mount`` (:data:`MOUNTS`, legacy by
    default). See :func:`almond_axol.settings.resolve_robot_model`;
    ``KinematicsConfig.robot_model`` overrides both.
    """

    CLASSIC = "classic"
    STANDALONE = "standalone"
    OX_CART = "ox_cart"
    OWL = "owl"
    MOBILE = "mobile"


MOUNTS: tuple[AxolModel, ...] = (
    AxolModel.CLASSIC,
    AxolModel.STANDALONE,
    AxolModel.OX_CART,
    AxolModel.OWL,
)
"""The versions to choose from when Jelly is not enabled (``kinematics.mount``);
the mobile Axol is never chosen, it follows Jelly."""


URDF_DIR: Path = Path(__file__).resolve().parent / "kinematics" / "urdf"
URDF_PATH: Path = URDF_DIR / "axol.urdf"
"""The classic URDF. Prefer :func:`urdf_path` for the robot's own version."""

_URDF_FILES: dict[AxolModel, str] = {
    AxolModel.CLASSIC: "axol.urdf",
    AxolModel.STANDALONE: "axol_standalone.urdf",
    AxolModel.OX_CART: "axol_ox_cart.urdf",
    AxolModel.OWL: "axol_owl.urdf",
    AxolModel.MOBILE: "axol_jelly.urdf",
}
# Whole-body IK model (mobile only): the same torso and arms on the Jelly's
# planar base and lift — see BODY_JOINTS.
_WHOLE_BODY_URDF = "axol_jelly_whole_body.urdf"
# The mobile Axol with the parcel gripper (AxolConfig.gripper = "parcel"):
# the same body and arms, the parcel gripper's jaw and hinged plate in place
# of the parallel gripper and its wrist camera.
_PARCEL_URDF = "axol_jelly_parcel.urdf"
_PARCEL_WHOLE_BODY_URDF = "axol_jelly_parcel_whole_body.urdf"

JELLY_SIM_URDF: Path = URDF_DIR / "axol_jelly_sim.urdf"
"""Axol on Jelly for physics simulators (e.g. Isaac Sim), not used by the stack.

Rooted at the Jelly on the floor, with the lift, coupled gripper fingers and
wheels as joints, AxolConfig's arm masses, per-part contact hulls, camera
optical frames (``*_optical``, ROS convention) and relative mesh paths. See
the header of the file for what is estimated.
"""

JELLY_PARCEL_SIM_URDF: Path = URDF_DIR / "axol_jelly_parcel_sim.urdf"
""":data:`JELLY_SIM_URDF` with the parcel gripper: each hinged plate is a
revolute joint (``left_plate_joint`` / ``right_plate_joint``)."""

BODY_JOINTS: tuple[str, ...] = ("base_x", "base_y", "base_yaw", "lift")
"""The Jelly joints whole-body IK solves for, after the 14 arm joints.

``base_x`` / ``base_y`` (m) and ``base_yaw`` (rad) move the base in the
plane about the Jelly centre, in the world frame of the session's start;
``lift`` (m) lowers each of the two lift stages from fully raised (0), so the
torso drops twice that. Wheel spin is not a pose: wheel speeds follow from
the base motion through the drive's kinematics.
"""

# Static body links the arms must not collide into, per version. pyroki fits
# one capsule per link, so the mobile body is split into capsule-friendly
# pieces: the shoulder bar, the lift column, the column's top plate and the
# head-camera mount. (The Jelly deck is out of reach with the lift raised and
# has no collision geometry — see axol_jelly.urdf's header.)
_TORSO_LINKS: dict[AxolModel, tuple[str, ...]] = {
    AxolModel.CLASSIC: ("base", "s1"),
    AxolModel.STANDALONE: ("s1", "head"),
    # The lift column (base); the caster frame is out of reach, lift raised.
    AxolModel.OX_CART: ("base", "s1", "head"),
    # The mount's column (base) and its foot plate as six strips.
    AxolModel.OWL: ("base", "s1", "head", *(f"foot_{i}" for i in range(6))),
    AxolModel.MOBILE: ("base", "s1", "lift_plate", "head"),
}
# With the lift moving, each column section rides its own stage and the deck
# comes within reach.
_WHOLE_BODY_TORSO_LINKS: tuple[str, ...] = (
    *_TORSO_LINKS[AxolModel.MOBILE],
    "lift_stage",
    "jelly",
    "deck_0",
    "deck_1",
    "deck_2",
)


def _check_whole_body(model: AxolModel | str) -> None:
    if AxolModel(model) is not AxolModel.MOBILE:
        raise ValueError(
            "whole-body IK needs the mobile Axol (its Jelly base and lift are "
            "the extra joints); the other versions have none"
        )


def urdf_path(
    model: AxolModel | str = AxolModel.CLASSIC,
    *,
    whole_body: bool = False,
    gripper: str = "parallel",
) -> Path:
    """The bundled URDF for ``model`` (meshes resolve relative to :data:`URDF_DIR`).

    ``whole_body`` selects the mobile model with the Jelly joints
    (:data:`BODY_JOINTS`) instead of the arms-only one. ``gripper``
    (``AxolConfig.gripper``) selects the mobile Axol's parcel-gripper model;
    the other versions have one URDF each, with the parallel gripper.
    """
    if whole_body:
        _check_whole_body(model)
    if gripper == "parcel" and AxolModel(model) is AxolModel.MOBILE:
        return URDF_DIR / (_PARCEL_WHOLE_BODY_URDF if whole_body else _PARCEL_URDF)
    if whole_body:
        return URDF_DIR / _WHOLE_BODY_URDF
    return URDF_DIR / _URDF_FILES[AxolModel(model)]


# The Owl mount's foot plate sits under the upper arms' path, behind them:
# its strip capsules overlap the upper arms' (fat) capsules at the arms'
# ordinary poses even though the parts clear by ~5 cm, so it is kept off
# the hard upper-arm guard (built for the upper arm swinging into the torso
# cross-body); the soft collision cost still keeps the arms off it.
_UPPER_ARM_GUARD_EXEMPT = frozenset(f"foot_{i}" for i in range(6))


def upper_arm_guard_links(
    model: AxolModel | str = AxolModel.CLASSIC, *, whole_body: bool = False
) -> tuple[str, ...]:
    """The body links the solver hard-stops the upper arms (e1) against: the
    :func:`torso_links` but the Owl mount's foot."""
    return tuple(
        link
        for link in torso_links(model, whole_body=whole_body)
        if link not in _UPPER_ARM_GUARD_EXEMPT
    )


def torso_links(
    model: AxolModel | str = AxolModel.CLASSIC, *, whole_body: bool = False
) -> tuple[str, ...]:
    """URDF links of ``model``'s body that arm links collide against."""
    if whole_body:
        _check_whole_body(model)
        return _WHOLE_BODY_TORSO_LINKS
    return _TORSO_LINKS[AxolModel(model)]


# Where the fingers close, in the gripper link frame (metres, FLU). The URDF
# chain ends at the gripper mount, which is what forward kinematics and the IK
# solver report; the gripper mesh runs 145 mm out along that link's -Z. Any
# code that cares where the *tool* is — rather than where it is bolted on —
# needs this offset, and the distance is large enough that ignoring it turns a
# straight-line move into a visible arc as the wrist reorients.
GRIPPER_TIP_OFFSET: tuple[float, float, float] = (0.0, 0.0, -0.145)


# Single source of truth for URDF joint and body names. All helpers
# (gravity comp, IK solver, simulation) compose ``f"{side}_{suffix}"`` from
# these tables via the ``urdf_*_name`` helpers below.

# ``Joint.GRIPPER`` is intentionally absent: the gripper is a fixed URDF
# joint with no actuator counterpart.
_ARM_JOINT_URDF_SUFFIX: dict[Joint, str] = {
    Joint.SHOULDER_1: "s1_0",
    Joint.SHOULDER_2: "s2_0",
    Joint.SHOULDER_3: "s3_0",
    Joint.ELBOW: "e1_0",
    Joint.WRIST_1: "e2_0",
    Joint.WRIST_2: "w1_0",
    Joint.WRIST_3: "w2_0",
}

# Body driven by each joint. ``Joint.GRIPPER`` maps to the (fixed-jointed)
# gripper link itself; MuJoCo merges this body into ``*_w2`` at load time.
_BODY_URDF_SUFFIX: dict[Joint, str] = {
    Joint.SHOULDER_1: "s2",
    Joint.SHOULDER_2: "s3",
    Joint.SHOULDER_3: "e1",
    Joint.ELBOW: "e2",
    Joint.WRIST_1: "w0",
    Joint.WRIST_2: "w1",
    Joint.WRIST_3: "w2",
    Joint.GRIPPER: "gripper",
}


def urdf_joint_name(joint: Joint, *, is_left: bool) -> str:
    """URDF revolute-joint name driving ``joint`` on the given arm.

    Example::

        urdf_joint_name(Joint.SHOULDER_1, is_left=True) == "left_s1_0"

    Raises ``KeyError`` for ``Joint.GRIPPER`` (no actuator joint in the URDF).
    """
    side = "left" if is_left else "right"
    return f"{side}_{_ARM_JOINT_URDF_SUFFIX[joint]}"


def urdf_body_name(joint: Joint, *, is_left: bool) -> str:
    """URDF body driven by ``joint`` on the given arm.

    Example::

        urdf_body_name(Joint.SHOULDER_1, is_left=True) == "left_s2"
        urdf_body_name(Joint.GRIPPER,    is_left=True) == "left_gripper"
    """
    side = "left" if is_left else "right"
    return f"{side}_{_BODY_URDF_SUFFIX[joint]}"


def urdf_arm_joint_names(*, is_left: bool) -> list[str]:
    """URDF revolute-joint names for the 7 arm joints, in :data:`ARM_JOINTS` order."""
    return [urdf_joint_name(j, is_left=is_left) for j in ARM_JOINTS]


def urdf_arm_body_names(*, is_left: bool) -> list[str]:
    """URDF bodies driven by the 7 arm joints, in :data:`ARM_JOINTS` order."""
    return [urdf_body_name(j, is_left=is_left) for j in ARM_JOINTS]
